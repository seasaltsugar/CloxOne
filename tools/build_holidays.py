#!/usr/bin/env python3
"""
Build CloxOne's bundled public-holiday data from python-holidays (MIT licence).

    pip install --upgrade holidays
    python3 tools/build_holidays.py              # 10 years from the current year
    python3 tools/build_holidays.py --years 12   # a different span
    python3 tools/build_holidays.py --start 2026 --years 10

Holidays are tracked per COUNTRY (national public holidays only, no state or
regional ones, no observances). Every country in tools/data/zone.tab that
python-holidays supports is included, so raw time zones get holidays too.

Writes extension/js/holidays-data.js in a compact format:
    data[CC] = { "n": [names...], "d": { "2026": "0101:0,0119:1,..." } }
Runs at build time only; nothing here ships in or runs inside the extension.
"""
import argparse
import datetime
import json
import pathlib
import sys

try:
    import holidays
except ImportError:
    sys.exit("python-holidays is not installed. Run: pip install --upgrade holidays")

ROOT = pathlib.Path(__file__).resolve().parent.parent
ZONE_TAB = ROOT / "tools" / "data" / "zone.tab"
OUT_JS = ROOT / "extension" / "js" / "holidays-data.js"
ENGLISH = ("en_US", "en_GB", "en_AU", "en_CA", "en_IN", "en_NZ", "en_PH", "en_SG", "en")


def countries():
    ccs = set()
    for line in ZONE_TAB.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            ccs.add(line.split("\t")[0].strip())
    supported = set(holidays.list_supported_countries().keys())
    return sorted(ccs & supported), sorted(ccs - supported)


def english_for(cc):
    probe = holidays.country_holidays(cc)
    langs = getattr(probe, "supported_languages", ()) or ()
    for lang in ENGLISH:
        if lang in langs:
            return lang
    return None


def build(cc, years):
    kwargs = dict(years=years, observed=True, categories=(holidays.PUBLIC,))
    lang = english_for(cc)
    if lang:
        kwargs["language"] = lang
    h = holidays.country_holidays(cc, **kwargs)  # national only: no subdiv
    names, name_idx, by_year = [], {}, {}
    for d, name in sorted(h.items()):
        if name not in name_idx:
            name_idx[name] = len(names)
            names.append(name)
        by_year.setdefault(str(d.year), []).append(f"{d:%m%d}:{name_idx[name]}")
    return {"n": names, "d": {y: ",".join(v) for y, v in by_year.items()}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", type=int, default=datetime.date.today().year)
    ap.add_argument("--years", type=int, default=10)
    args = ap.parse_args()
    years = list(range(args.start, args.start + args.years))

    ok, unsupported = countries()
    data, notes = {}, []
    for cc in ok:
        try:
            entry = build(cc, years)
        except Exception as e:  # pragma: no cover
            notes.append(f"{cc}: skipped ({e.__class__.__name__}: {e})")
            continue
        if entry["n"]:
            data[cc] = entry

    payload = {
        "source": f"python-holidays {holidays.__version__} (MIT)",
        "generated": datetime.date.today().isoformat(),
        "years": years,
        "data": data,
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    OUT_JS.write_text(
        "// Generated by tools/build_holidays.py from python-holidays (MIT). Do not edit by hand.\n"
        f"globalThis.CLOX_HOLIDAYS = {body};\n",
        encoding="utf-8",
    )
    kb = OUT_JS.stat().st_size / 1024
    print(f"Wrote {OUT_JS.relative_to(ROOT)}: {len(data)} countries, {years[0]}-{years[-1]}, {kb:.0f} KB")
    if unsupported:
        print(f"  no python-holidays data for {len(unsupported)} codes (badges hidden there): {' '.join(unsupported)}")
    for n in notes:
        print("  note:", n)
    print("  reminder: lunar/Islamic and government-announced holidays far in the future are estimates;")
    print("  rebuild with a newer python-holidays from time to time to pick up corrections.")


if __name__ == "__main__":
    main()
